import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const inputPath = process.argv.find((arg) => !arg.startsWith("--") && arg !== process.argv[0] && arg !== process.argv[1])
  ? resolve(process.cwd(), process.argv.find((arg) => !arg.startsWith("--") && arg !== process.argv[0] && arg !== process.argv[1]))
  : resolve(root, "openapi/control-plane.json");
const outputPath = resolve(root, "src/generated/control_plane.d.ts");
const checkOnly = process.argv.includes("--check");

if (!existsSync(inputPath)) {
  throw new Error(`OpenAPI input not found: ${inputPath}`);
}

const document = JSON.parse(readFileSync(inputPath, "utf8"));
const generated = `/**
 * This file was auto-generated by openapi-typescript.
 * Do not make direct changes to the file.
 */

${astToString(await openapiTS(document, { alphabetize: true }))}`;
const current = existsSync(outputPath) ? readFileSync(outputPath, "utf8") : "";

if (checkOnly) {
  if (current !== generated) {
    console.error(`Generated API types are stale. Run pnpm generate:api-types in ${root}.`);
    process.exitCode = 1;
  }
} else {
  writeFileSync(outputPath, generated);
  console.log(`Generated ${outputPath} from ${inputPath}`);
}
